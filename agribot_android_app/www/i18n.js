  function lang() {
    const saved = localStorage.getItem(STORAGE_KEY) || "en";
    return STRINGS[saved] ? saved : "en";
  }

  function normalize(value) {
    return String(value || "").toLowerCase().replace(/[_-]/g, " ").trim();
  }

  function t(key, params = {}) {
    const text = (STRINGS[lang()] && STRINGS[lang()][key]) || STRINGS.en[key] || key;
    return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
  }

  function label(value) {
    const key = normalize(value);
    return (LABELS[lang()] && LABELS[lang()][key]) || LABELS.en[key] || String(value || "--").replace(/_/g, " ");
  }

  function action(value, row = {}) {
    const normalized = normalize(value || row.action);
    if (normalized === "inspect or treat") return t("inspectOrTreat");
    if (normalized === "rescan this plant") return t("rescanThisPlant");
    if (normalized === "no action") return t("noAction");
    if (row.status === "uncertain") return t("rescanThisPlant");
    if (normalize(row.label) === "healthy") return t("noAction");
    return value ? String(value) : t("inspectOrTreat");
  }

  function status(value) {
    const key = normalize(value);
    if (key === "ok") return t("ok");
    if (key === "uncertain") return t("uncertain");
    return value || "--";
  }

  function reason(value) {
    const key = normalize(value);
    if (key === "primary agreement") return t("primaryAgreement");
    if (key === "backup majority") return t("backupMajority");
    if (key === "low confidence") return t("lowConfidence");
    if (key === "disagreement") return t("disagreement");
    return value ? String(value).replace(/_/g, " ") : "";
  }

  function plantName(row) {
    const field = row.field_id || "";
    const rowId = row.row_id || "A";
    const plant = row.plant_number ?? row.plant_id ?? row.sequence ?? "--";
    return `${field ? `${field} / ` : ""}${t("row")} ${rowId} / ${t("plant")} ${plant}`;
  }

  function apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.title = t(node.dataset.i18nTitle);
    });
    document.documentElement.lang = lang();
    document.documentElement.dir = (LANGUAGES.find(([code]) => code === lang()) || [])[3] || "ltr";
  }

  function init(select, onChange) {
    if (!select) return;
    select.replaceChildren();
    for (const [code, nativeName, englishName] of LANGUAGES) {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = nativeName === englishName ? nativeName : `${nativeName} / ${englishName}`;
      select.appendChild(option);
    }
    select.value = lang();
    select.addEventListener("change", () => {
      localStorage.setItem(STORAGE_KEY, select.value);
      apply(document);
      if (typeof onChange === "function") onChange();
    });
    apply(document);
  }

  window.AgribotI18N = { init, apply, t, label, action, status, reason, plantName, lang };
